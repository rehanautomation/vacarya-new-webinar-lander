#!/usr/bin/env python3
"""Build paste-ready GHL Custom Code blocks from the Vercel pages.

  python3 tools/build-ghl.py

Writes ghl/<step>.html. Each file is ONE block to paste into a GHL funnel step
(Custom JS/HTML element, full width). What changes vs. the Vercel page:
  - no <html>/<head>/<body> wrapper, no title/meta/favicon (set those in GHL page settings)
  - images, PDF and API calls point at the Vercel back end (absolute URLs)
  - page-to-page links point at the GHL funnel steps on SITE
  - review-only Back/Next bar removed
  - a small script removes GHL's section/row padding so the page is full width
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = 'https://event.hostvacarya.com'               # GHL funnel domain
API = 'https://new-webinar-lander.vercel.app'       # Vercel back end (API, images, PDF): existing project, Stripe keys already set

PAGES = {  # Vercel file -> GHL step path
    'index.html': 'register',
    'vip.html': 'vip',
    'vip-application.html': 'vip-application',
    'vip-confirmed.html': 'vip-confirmed',
    'confirmed.html': 'confirmed',
}

KEEP_HEAD = re.compile(r'<link[^>]*(?:preconnect|dns-prefetch|stylesheet)[^>]*>|<style[\s\S]*?</style>|<script[\s\S]*?</script>', re.I)

STRIP = '''<script>
/* GHL: drop the builder's section/row/column padding so this page runs full width */
(function(){
  var root = document.getElementById('%s');
  if (!root) return;
  var n = root.parentElement;
  while (n && n !== document.body) { n.style.padding = '0'; n.style.margin = '0'; n.style.maxWidth = 'none'; n = n.parentElement; }
  document.documentElement.style.overflowX = 'clip'; document.body.style.overflowX = 'clip';
  document.body.style.margin = '0'; document.body.style.background = '#FFFFFF';
})();
</script>'''


def build(src, step):
    s = (ROOT / src).read_text()
    head = s[s.index('<head>') + 6:s.index('</head>')]
    body = s[s.index('<body'):]
    body = body[body.index('>') + 1:body.rindex('</body>')]
    keep = '\n'.join(m.group(0) for m in KEEP_HEAD.finditer(head))
    out = keep + '\n' + body.strip() + '\n'

    # review-only nav
    out = out.replace('<script src="/flow-nav.js" defer></script>', '')
    # Vercel back end: assets + API
    out = re.sub(r'''(["'(])/(img|downloads|api)/''', lambda m: m.group(1) + API + '/' + m.group(2) + '/', out)
    # funnel links
    out = re.sub(r'''(["'])/(confirmed|vip-application|vip-confirmed|vip|register)(?=["'?#])''', lambda m: m.group(1) + SITE + '/' + m.group(2), out)
    # vip-confirmed: this undo-rule was only for the bare Vercel page
    out = out.replace('/* this page has no GHL wrapper: undo the full-bleed 100vw trick (it caused sideways scroll) */\n#vc-vip{width:auto;left:auto;right:auto;margin:0}\n', '')

    root = re.search(r'<div id="(vc-reg|vc-vip|pq|vc-ok)"', out).group(1)
    out += STRIP % root + '\n'

    left = re.findall(r'''(?:src|href)=["']/(?!/)[^"']*|fetch\(['"]/''', out)
    assert not left, (src, left)
    (ROOT / 'ghl').mkdir(exist_ok=True)
    (ROOT / 'ghl' / f'{step}.html').write_text(f'<!-- GHL step: {SITE}/{step}  (generated by tools/build-ghl.py from {src}; edit the source, not this file) -->\n' + out)
    return len(out)


if __name__ == '__main__':
    for src, step in PAGES.items():
        print(f'{step:16} {build(src, step):>8} chars')
